using ContractWatcher.MicroDb.Options;

namespace ContractWatcher.MicroDb.Interfaces;

/// <summary>
/// Представляет внутренний контракт набора сущностей,
/// состояние которого может быть сохранено в постоянное хранилище.
/// </summary>
/// <remarks>
/// <para>
/// Интерфейс используется <see cref="MicroDbContext"/>
/// для унифицированной работы с наборами сущностей независимо
/// от их конкретных типов сущности и ключа.
/// </para>
/// <para>
/// Каждый набор самостоятельно отслеживает наличие изменений относительно
/// последнего успешно сохранённого состояния и отвечает за сохранение этих
/// изменений в соответствующее ему хранилище.
/// </para>
/// <para>
/// Каждому набору сущностей соответствует
/// отдельный файл постоянного хранилища.
/// Файлы наборов располагаются в директории,
/// указанной в <see cref="MicroDbOptions.DirectoryPath"/>.
/// </para>
/// </remarks>
internal interface IMicroDbSet : IDisposable
{
    /// <summary>
    /// Возвращает значение, указывающее, содержит ли набор изменения,
    /// которые ещё не были успешно сохранены в постоянное хранилище.
    /// </summary>
    /// <value>
    /// <c>true</c>, если текущее состояние набора отличается
    /// от последнего успешно сохранённого состояния, иначе - <c>false</c>
    /// </value>
    /// <remarks>
    /// <para>
    /// После успешного сохранения текущего состояния свойство возвращает
    /// <c>false</c>, если во время операции сохранения не появились новые изменения.
    /// </para>
    /// <para>
    /// Если состояние набора было изменено параллельно с сохранением,
    /// новые изменения остаются несохранёнными и свойство продолжает возвращать <c>true</c>.
    /// </para>
    /// </remarks>
    bool HasChanges { get; }

    /// <summary>
    /// Асинхронно сохраняет текущее изменённое состояние набора
    /// в постоянное хранилище.
    /// </summary>
    /// <param name="cancellationToken">Токен для отмены операции сохранения.</param>
    /// <returns>
    /// Задача, результатом которой является количество изменений,
    /// вошедших в успешно сохранённое состояние.
    /// 
    /// Если набор не содержит несохранённых изменений, возвращается <c>0</c>.
    /// </returns>
    /// <remarks>
    /// <para>
    /// Операция сохраняет согласованный снимок состояния набора,
    /// существовавший на момент начала сохранения.
    /// </para>
    /// <para>
    /// Изменения, выполненные параллельно после получения этого снимка,
    /// не теряются и должны быть сохранены последующим
    /// вызовом <see cref="SaveChangesAsync"/>.
    /// </para>
    /// <para>
    /// Неудачная операция сохранения не должна помечать изменения
    /// как успешно сохранённые, что позволяет повторить вызов позднее.
    /// </para>
    /// </remarks>
    /// <exception cref="OperationCanceledException">
    /// Операция была отменена через <paramref name="cancellationToken"/>.
    /// </exception>
    Task<int> SaveChangesAsync(CancellationToken cancellationToken = default);
}