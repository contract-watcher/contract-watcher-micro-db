namespace ContractWatcher.MicroDb.Tracking.Enums;

/// <summary>
/// Описывает состояние сущности относительно
/// последнего успешно сохранённого состояния.
/// </summary>
public enum EntityState
{
    /// <summary>
    /// Текущее сохраняемое содержимое сущности
    /// совпадает с baseline по fingerprint.
    /// </summary>
    Unchanged,

    /// <summary>
    /// Сущность присутствует в текущем наборе,
    /// но отсутствует в последнем сохранённом состоянии.
    /// </summary>
    Added,

    /// <summary>
    /// Сущность присутствует в текущем наборе и baseline,
    /// но её текущий fingerprint отличается от сохранённого.
    /// </summary>
    Modified,

    /// <summary>
    /// Сущность удалена из текущего набора,
    /// но ещё присутствует в последнем сохранённом состоянии.
    /// </summary>
    Deleted,

    /// <summary>
    /// Запись отсутствует и в текущем наборе,
    /// и в последнем сохранённом состоянии.
    /// </summary>
    /// <remarks>
    /// Например, сущность добавили и удалили до сохранения
    /// либо её удаление уже успешно сохранено.
    /// Несохранённых операций для такого ключа нет.
    /// </remarks>
    Detached
}