using ContractWatcher.MicroDb.Tracking.Enums;

namespace ContractWatcher.MicroDb.Tracking.Abstractions;

/// <summary>
/// Определяет источник уведомлений об изменении
/// сохраняемого состояния сущности.
/// </summary>
/// <remarks>
/// <para>
/// Интерфейс используется режимом <see cref="ChangeTrackingMode.Events"/>.
/// </para>
/// <para>
/// Событие <see cref="Changed"/> не описывает конкретное
/// изменённое свойство и не означает, что сущность обязательно
/// отличается от последнего сохранённого состояния.
/// </para>
/// <para>
/// Полученное событие только помечает сущность как потенциально
/// изменённую. Фактическое состояние определяется Change Tracker
/// позднее путём сравнения fingerprints текущего и последнего
/// успешно сохранённого JSON-представления.
/// </para>
/// <para>
/// Если сущность содержит изменяемые вложенные объекты
/// или коллекции, корневая сущность самостоятельно отвечает
/// за проброс их изменений через <see cref="Changed"/>.
/// </para>
/// </remarks>
public interface IEntityChangeSource
{
    /// <summary>
    /// Возникает после потенциального изменения
    /// сохраняемого состояния сущности.
    /// </summary>
    event EventHandler? Changed;
}