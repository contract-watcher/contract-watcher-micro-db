using System.Text.Json;

namespace ContractWatcher.MicroDb.Options;

/// <summary>
/// Содержит параметры конфигурации локального хранилища <c>MicroDB</c>.
/// </summary>
/// <remarks>
/// <para>
/// Настройки определяют расположение файлов базы и
/// правила JSON-сериализации сущностей.
/// </para>
/// <para>
/// MicroDB использует файловую модель хранения:
/// каждый зарегистрированный набор сущностей
/// сохраняется в отдельный JSON-файл внутри директории,
/// указанной в <see cref="DirectoryPath"/>.
/// </para>
/// </remarks>
public sealed class MicroDbOptions
{
    /// <summary>
    /// Получает путь к директории,
    /// используемой для хранения файлов <c>MicroDB</c>.
    /// </summary>
    /// <value>Абсолютный или относительный путь
    /// к директории локального хранилища.</value>
    /// <remarks>
    /// <para>
    /// В указанной директории <c>MicroDB</c> создаёт отдельный файл
    /// для каждого зарегистрированного набора сущностей.
    /// </para>
    /// <para>
    /// Если используется относительный путь, его разрешение выполняется
    /// относительно рабочей директории текущего процесса.
    /// </para>
    /// <para>
    /// Директория может быть создана <c>MicroDB</c> автоматически
    /// при инициализации контекста.
    /// </para>
    /// </remarks>
    public required string DirectoryPath { get; init; }

    /// <summary>
    /// Получает параметры, используемые для сериализации
    /// и десериализации данных <c>MicroDB</c> в формате JSON.
    /// </summary>
    /// <value>Экземпляр <see cref="JsonSerializerOptions"/>,
    /// используемый файловым хранилищем.</value>
    /// <remarks>
    /// <para>
    /// По умолчанию используются настройки
    /// <see cref="JsonSerializerDefaults.Web"/>.
    /// </para>
    /// <para>
    /// Свойство позволяет настроить поведение сериализатора,
    /// например зарегистрировать пользовательские converters,
    /// изменить правила именования свойств или настроить обработку enum.
    /// </para>
    /// <para>
    /// Одни и те же настройки должны использоваться как при записи,
    /// так и при последующем чтении файлов базы.
    /// Изменение несовместимых параметров сериализации после создания
    /// данных может привести к невозможности корректно
    /// восстановить ранее сохранённое состояние.
    /// </para>
    /// </remarks>
    public JsonSerializerOptions JsonSerializerOptions { get; init; } = new(JsonSerializerDefaults.Web);
}