using System.Text.Json;

namespace ContractWatcher.MicroDb.Options;

/// <summary>
/// Содержит параметры конфигурации локального хранилища MicroDB.
/// </summary>
/// <remarks>
/// Настройки определяют расположение файлов базы и правила JSON-сериализации сущностей.
/// 
/// MicroDB использует файловую модель хранения:
/// каждый зарегистрированный набор сущностей сохраняется в отдельный JSON-файл внутри директории,
/// указанной в <see cref="DirectoryPath"/>.
/// </remarks>
public sealed class MicroDbOptions
{
    /// <summary>
    /// Получает путь к директории, используемой для хранения файлов MicroDB.
    /// </summary>
    /// <value>Абсолютный или относительный путь к директории локального хранилища.</value>
    /// <remarks>
    /// В указанной директории MicroDB создаёт отдельный файл для каждого зарегистрированного набора сущностей.
    /// 
    /// Например, набор с именем <c>users</c> может быть сохранён как:
    /// <code>{DirectoryPath}/users.json</code>
    /// 
    /// Если используется относительный путь, его разрешение выполняется
    /// относительно рабочей директории текущего процесса.
    /// 
    /// Директория может быть создана MicroDB автоматически при инициализации контекста.
    /// </remarks>
    public required string DirectoryPath { get; init; }

    /// <summary>
    /// Получает параметры, используемые для сериализации
    /// и десериализации данных MicroDB в формате JSON.
    /// </summary>
    /// <value>Экземпляр <see cref="JsonSerializerOptions"/>, используемый файловым хранилищем.
    /// </value>
    /// <remarks>
    /// По умолчанию используются настройки <see cref="JsonSerializerDefaults.Web"/>.
    /// 
    /// Свойство позволяет настроить поведение сериализатора,
    /// например зарегистрировать пользовательские converters,
    /// изменить правила именования свойств или настроить обработку enum.
    /// 
    /// Одни и те же настройки должны использоваться как при записи, так и при последующем чтении файлов базы.
    /// Изменение несовместимых параметров сериализации после создания
    /// данных может привести к невозможности корректно восстановить ранее сохранённое состояние.
    /// </remarks>
    public JsonSerializerOptions JsonSerializerOptions { get; init; } = new(JsonSerializerDefaults.Web);
}